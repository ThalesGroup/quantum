// Syntax highlighting with Shiki, shared by the build (frontmatter) and the browser (playground).
// Synchronous core + JavaScript regex engine + a fixed set of grammars: no WASM, no async setup,
// and the client bundle only carries what is imported here.
import { createHighlighterCoreSync, hastToHtml } from 'shiki/core';
import { createJavaScriptRegexEngine } from 'shiki/engine/javascript';
import { transformerNotationDiff, transformerNotationErrorLevel, transformerNotationHighlight } from '@shikijs/transformers';
import css from 'shiki/langs/css.mjs';
import diff from 'shiki/langs/diff.mjs';
import html from 'shiki/langs/html.mjs';
import javascript from 'shiki/langs/javascript.mjs';
import json from 'shiki/langs/json.mjs';
import markdown from 'shiki/langs/markdown.mjs';
import shellscript from 'shiki/langs/shellscript.mjs';
import yaml from 'shiki/langs/yaml.mjs';
import theme from '@quantum-ds/tokens/shiki-theme.json';

/**
 * The design system's theme (Code foundation), generated by `pnpm tokens:build`: its colors are
 * the CSS variables of the code tokens, so one theme follows the mode of every data-theme context.
 * astro.config.mjs gives the same theme to the Markdown docs.
 */
export const THEME = theme.name;

/**
 * Shiki's notation transformers: `[!code highlight]`, `[!code ++]`, `[!code --]`, `[!code error]`
 * and `[!code warning]` in a comment mark the line (and disappear from the output); the design
 * system's web/foundations/code.css draws the marked lines. astro.config.mjs uses the same list.
 */
export const transformers = () => [transformerNotationHighlight(), transformerNotationDiff(), transformerNotationErrorLevel()];

const highlighter = createHighlighterCoreSync({
  themes: [theme as any],
  langs: [css, diff, html, javascript, json, markdown, shellscript, yaml],
  engine: createJavaScriptRegexEngine(),
});

const ALIASES: Record<string, string> = { js: 'javascript', mjs: 'javascript', sh: 'shellscript', bash: 'shellscript', shell: 'shellscript', yml: 'yaml', md: 'markdown', patch: 'diff' };

export type Lang = 'css' | 'diff' | 'html' | 'javascript' | 'json' | 'markdown' | 'shellscript' | 'yaml';

const escapeHtml = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/** Resolves a fence info string or file extension to a loaded grammar, or null. */
export function langOf(name: string | undefined | null): Lang | null {
  const key = (name ?? '').trim().toLowerCase().replace(/^\./, '');
  const lang = ALIASES[key] ?? key;
  return highlighter.getLoadedLanguages().includes(lang) ? (lang as Lang) : null;
}

/** Language of a repository file, from its extension (`web/components/button/button.css` -> css). */
export const langOfFile = (path: string) => langOf(path.split('.').pop());

/**
 * Highlighted tokens for the inside of a `<code>` element. Lines stay separated by real newlines,
 * so `textContent` (copy buttons) returns the source, without its notation comments. Unknown
 * languages are escaped only.
 */
export function highlight(code: string, lang: string | null | undefined): string {
  const resolved = langOf(lang);
  if (!resolved) return escapeHtml(code);
  const root = highlighter.codeToHast(code, { lang: resolved, theme: THEME, transformers: transformers() });
  const pre = root.children[0] as any;
  const codeEl = pre.children[0];
  return hastToHtml(codeEl.children);
}
