import { defineConfig } from 'astro/config';
import repoSources from './integrations/repo-sources.mjs';
import { transformerNotationDiff, transformerNotationErrorLevel, transformerNotationHighlight } from '@shikijs/transformers';
import theme from '@quantum-ds/tokens/shiki-theme.json' with { type: 'json' };

// The site is a viewer only. All design knowledge lives in the packages (tokens, components) and in content/.
export default defineConfig({
  site: process.env.SITE_URL,
  base: process.env.SITE_BASE ?? '/',
  outDir: './dist',
  compressHTML: false,
  // The design system's Shiki theme (Code foundation, generated by pnpm tokens:build), as in
  // src/lib/highlight.ts, which highlights every other code block of the site.
  // Same notation transformers too (line states drawn by ../web/foundations/code.css).
  markdown: { shikiConfig: { theme, transformers: [transformerNotationHighlight(), transformerNotationDiff(), transformerNotationErrorLevel()] } },
  // Dev only: reload the sibling sources, also after a restart caused by an edit of this file.
  integrations: [repoSources()],
  vite: {
    server: {
      // Allow the dev server to read the whole monorepo (the packages, the agent guides).
      fs: { allow: ['../..'] },
    },
    // Vite discovers the dependencies of client scripts only when a page first requests them; it
    // then re-optimizes and leaves open pages requesting stale hashes (504 "Outdated Optimize
    // Dep"), which breaks their scripts. Pre-bundling every client-side dependency at startup
    // avoids the re-optimization. Keep in sync with the bare imports of client scripts: the
    // anatomy (src/components/Anatomy.astro) and src/lib/highlight.ts (playground).
    optimizeDeps: {
      include: [
        '@component-anatomy/core',
        'shiki/core',
        'shiki/engine/javascript',
        '@shikijs/transformers',
        'shiki/langs/css.mjs',
        'shiki/langs/diff.mjs',
        'shiki/langs/html.mjs',
        'shiki/langs/javascript.mjs',
        'shiki/langs/json.mjs',
        'shiki/langs/markdown.mjs',
        'shiki/langs/shellscript.mjs',
        'shiki/langs/yaml.mjs',
      ],
    },
  },
});
