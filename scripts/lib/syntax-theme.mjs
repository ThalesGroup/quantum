/**
 * Syntax highlighting theme generated from the tokens (Code foundation).
 * Zero dependencies. Used by build-tokens.mjs and its tests.
 *
 * tokens.config.json → `syntax` maps TextMate scopes to color tokens. The output is one theme in
 * the TextMate / VS Code theme format that Shiki reads (name, type, colors, tokenColors), whose
 * colors are CSS custom properties (`var(--global-text-code-keyword)`): a single theme follows every
 * mode through `data-theme`, with no light/dark pair. TextMate picks the most specific scope, so
 * `keyword.operator` overrides `keyword` whatever the order of the rules.
 */
import { cssVarName } from './dtcg.mjs';

const SCOPE_RE = /^[A-Za-z0-9_-]+(\.[A-Za-z0-9_+-]+)*( [A-Za-z0-9_-]+(\.[A-Za-z0-9_+-]+)*)*$/;
const matches = (pattern, p) => (pattern.endsWith('.*') ? p.startsWith(pattern.slice(0, -1)) : p === pattern);

/**
 * Problems of the `syntax` configuration, in the shape of checkReferences: every token named must
 * exist, be a color and belong to the semantic tier; every token matching `covers` must have a rule;
 * a scope belongs to one rule only.
 * @returns {{ token: string, file: string, message: string }[]}
 */
export function checkSyntax(loaded) {
  const cfg = loaded.config.syntax;
  if (!cfg) return [];
  const problems = [];
  const at = (token, message) => problems.push({ token, file: 'tokens.config.json', message: `syntax: ${message}` });
  const color = (p, role) => {
    const t = loaded.byPath.get(p);
    if (!t) return at(p, `${role} names an unknown token`);
    if (t.type !== 'color') at(p, `${role} must be a color token, not ${t.type}`);
    if (t.tier !== 'semantic') at(p, `${role} must be a semantic token, not a ${t.tier} token`);
  };
  if (!cfg.output) at('syntax', 'output is required');
  if (!cfg.name) at('syntax', 'name is required');
  color(cfg.foreground, 'foreground');
  color(cfg.background, 'background');
  const seen = new Map();
  for (const rule of cfg.rules ?? []) {
    color(rule.token, 'rule token');
    if (!rule.scopes?.length) at(rule.token, 'a rule needs at least one scope');
    for (const s of rule.scopes ?? []) {
      if (!SCOPE_RE.test(s)) at(rule.token, `"${s}" is not a TextMate scope selector`);
      if (seen.has(s)) at(rule.token, `scope "${s}" is already mapped to ${seen.get(s)}`);
      seen.set(s, rule.token);
    }
  }
  if (cfg.covers) {
    const mapped = new Set((cfg.rules ?? []).map((r) => r.token));
    for (const t of loaded.all) if (matches(cfg.covers, t.path) && !mapped.has(t.path)) at(t.path, `token matches covers "${cfg.covers}" but no rule maps a scope to it`);
  }
  return problems;
}

/**
 * The theme object. `type` is the scheme of the default mode: Shiki needs one, the colors follow
 * the mode of each context anyway.
 */
export function syntaxTheme(loaded) {
  const cfg = loaded.config.syntax;
  const prefix = loaded.config.css?.prefix ?? '';
  const v = (p) => `var(${cssVarName(p, prefix)})`;
  const scheme = (loaded.modes ?? []).find((m) => m.default)?.scheme ?? 'light';
  return {
    $comment: 'GENERATED by scripts/build-tokens.mjs from tokens.config.json (syntax) and the color tokens it names. Do not edit by hand; run "pnpm tokens:build". Colors are the CSS custom properties of @quantum-ds/tokens: load its css/index.css (or css/raw.css and css/semantic.css) on the page.',
    name: cfg.name,
    displayName: cfg.displayName ?? cfg.name,
    type: scheme,
    colors: { 'editor.foreground': v(cfg.foreground), 'editor.background': v(cfg.background) },
    tokenColors: (cfg.rules ?? []).map((r) => ({ name: r.token, scope: r.scopes, settings: { foreground: v(r.token) } })),
  };
}

/** Output files of the syntax theme: Map<absolutePath, text>. Empty without `syntax`. */
export function planSyntaxOutputs(loaded, resolve) {
  const cfg = loaded.config.syntax;
  return new Map(cfg ? [[resolve(cfg.output), `${JSON.stringify(syntaxTheme(loaded), null, 2)}\n`]] : []);
}
