#!/usr/bin/env node
/**
 * Regenerate specs/a11y/wcag.json from the W3C's machine-readable WCAG 2.2
 * (https://www.w3.org/WAI/WCAG22/wcag.json). Never edit wcag.json by hand.
 *   pnpm a11y:wcag
 * Needs network access; it is not part of `pnpm check`.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = 'https://www.w3.org/WAI/WCAG22/wcag.json';
const out = path.join(root, 'specs/a11y/wcag.json');

const res = await fetch(SOURCE);
if (!res.ok) {
  console.error(`GET ${SOURCE} -> ${res.status}`);
  process.exit(1);
}
const data = await res.json();

const criteria = {};
for (const principle of data.principles) {
  for (const guideline of principle.guidelines) {
    for (const sc of guideline.successcriteria) {
      criteria[sc.num] = {
        title: sc.handle,
        // Removed criteria (4.1.1 Parsing) have an empty level and are not part of 2.2.
        level: sc.level || null,
        slug: sc.id,
        inWcag22: sc.versions.includes('2.2'),
      };
    }
  }
}

const previous = fs.existsSync(out) ? JSON.parse(fs.readFileSync(out, 'utf8')) : null;
const doc = {
  $description: 'GENERATED by scripts/a11y-wcag.mjs from the W3C machine-readable WCAG 2.2. Do not edit. Referenced from specs as "wcag:<number>".',
  source: SOURCE,
  retrieved: new Date().toISOString().slice(0, 10),
  version: '2.2',
  recommendation: 'https://www.w3.org/TR/WCAG22/',
  understanding: 'https://www.w3.org/WAI/WCAG22/Understanding/{slug}.html',
  criteria,
};
if (previous && JSON.stringify(previous.criteria) === JSON.stringify(criteria)) doc.retrieved = previous.retrieved;
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, JSON.stringify(doc, null, 2) + '\n');
console.log(`Wrote ${path.relative(root, out)}: ${Object.keys(criteria).length} success criteria (${Object.values(criteria).filter((c) => c.inWcag22).length} in WCAG 2.2).`);
