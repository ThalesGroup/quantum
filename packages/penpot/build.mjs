#!/usr/bin/env node
/**
 * Components -> a Penpot plugin that draws them as components with variants bound to Penpot
 * design tokens (src/plan.mjs for the plan, src/plugin.js for the drawing).
 *
 *   node build.mjs [id…]    write dist/ (default: every component with a blueprint)
 *
 * dist/ holds manifest.json, plugin.js (the plugin with its plan), index.html (the plugin window,
 * built with the design system) and plan.json (the plan, to read). It reads the outputs of
 * packages/tokens/dist/ (the Penpot token file and the token CSS), so run `pnpm tokens:build`
 * first, as `pnpm penpot:export` and `pnpm build` do. Penpot loads a plugin over HTTP:
 * `pnpm penpot:serve` serves dist/, then in Penpot the plugin manager (Ctrl + Alt + P) installs
 * http://localhost:4400/manifest.json. Not committed (dist/ is ignored).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadAll } from '../../scripts/lib/dtcg.mjs';
import { MANIFEST, penpotPlan } from './src/plan.mjs';
import { BLUEPRINTS } from '../figma/src/blueprints/index.mjs';
import { renderUi, UI_COMPONENTS } from './src/ui/ui.mjs';
import { PATHS, FILES, artifacts } from '../../scripts/lib/paths.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = path.join(ROOT, PATHS.penpotDist);

function main() {
  const ids = process.argv.slice(2);
  const wanted = ids.length ? ids : Object.keys(BLUEPRINTS);
  const unknown = wanted.filter((id) => !BLUEPRINTS[id]);
  if (unknown.length) {
    console.error(`No blueprint for ${unknown.join(', ')}. Components it can draw: ${Object.keys(BLUEPRINTS).join(', ')}.`);
    process.exit(1);
  }
  // The components whose copies a blueprint uses are drawn too, first.
  const drawn = new Set();
  const add = (id) => {
    if (drawn.has(id)) return;
    (BLUEPRINTS[id].uses ?? []).forEach(add);
    drawn.add(id);
  };
  wanted.forEach(add);
  const read = (file) => {
    const full = path.join(ROOT, file);
    if (!fs.existsSync(full)) {
      console.error(`${file} is missing: run pnpm tokens:build first.`);
      process.exit(1);
    }
    return fs.readFileSync(full, 'utf8');
  };
  const loaded = loadAll(path.join(ROOT, PATHS.tokens));
  const specs = [...drawn].map((id) => JSON.parse(fs.readFileSync(path.join(ROOT, artifacts(id).spec), 'utf8')));
  const plan = penpotPlan(loaded, specs, BLUEPRINTS, JSON.parse(read(FILES.penpotTokens)));
  const plugin = fs.readFileSync(path.join(ROOT, PATHS.penpot, 'src/plugin.js'), 'utf8');
  const ui = renderUi(plan, {
    fonts: read(FILES.webFontsCss),
    css: [
      `${PATHS.tokensCss}/raw.css`,
      `${PATHS.tokensCss}/semantic.css`,
      ...UI_COMPONENTS.map((id) => artifacts(id).generated),
      ...UI_COMPONENTS.map((id) => artifacts(id).css),
    ].map(read).join('\n'),
  });

  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(OUT, { recursive: true });
  fs.writeFileSync(path.join(OUT, 'manifest.json'), `${JSON.stringify(MANIFEST, null, 2)}\n`);
  fs.writeFileSync(path.join(OUT, 'index.html'), ui);
  fs.writeFileSync(path.join(OUT, 'plan.json'), `${JSON.stringify(plan, null, 2)}\n`);
  fs.writeFileSync(path.join(OUT, 'plugin.js'), `// Generated by @quantum-ds/penpot (build.mjs: ${[...drawn].join(', ')}): do not edit.\nconst PLAN = ${JSON.stringify(plan)};\n\n${plugin}`);

  const rel = path.relative(ROOT, OUT);
  for (const c of plan.components) {
    const unbound = c.unbound.reduce((n, u) => n + u.tokens.length, 0);
    console.log(`${c.name} ${c.version}: ${c.variants.length} variants${c.uncovered.length ? ` (not drawn, not listed: ${c.uncovered.join(', ')})` : ''}${unbound ? `, ${unbound} tokens set to their value (plan.json: unbound)` : ''}`);
  }
  console.log(`${plan.tokens.tokens.length} tokens in ${plan.tokens.sets.join(', ')}; themes ${plan.tokens.themes.map((t) => `${t.group}/${t.name}`).join(', ')}`);
  console.log(`Wrote ${rel}/. Serve it with pnpm penpot:serve, then install http://localhost:4400/manifest.json in Penpot's plugin manager (Ctrl + Alt + P).`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
