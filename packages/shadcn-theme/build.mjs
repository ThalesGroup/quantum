#!/usr/bin/env node
/**
 * The Quantum tokens -> a shadcn/ui theme, through shadcn's own theming API only (its CSS
 * variables and a registry theme item), from the mapping table of src/mapping.mjs.
 *
 *   node packages/shadcn-theme/build.mjs            write dist/ (theme files, then the demo)
 *   node packages/shadcn-theme/build.mjs --no-demo  the theme files only
 *
 * dist/quantum.css   `:root` (light) and `.dark` variables, and the `@theme inline` bridge
 *                    to Tailwind, each value followed by the Quantum token it comes from
 * dist/quantum.json  the same variables as a shadcn registry item (`registry:theme`), for
 *                    `npx shadcn add <path-or-url>/quantum.json`
 * dist/demo.html     every shadcn component the demo shows, themed: one self-contained page
 *                    built from demo/ by Vite (the only build step with dependencies)
 *
 * Throws when the mapping names a token or a spec id that does not exist (src/lib.mjs). Reads
 * the token sources through scripts/lib/dtcg.mjs, so it needs no token build. Not committed
 * (dist/ is ignored): `pnpm --filter @quantum-ds/shadcn-theme build` writes it again.
 */
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import * as mapping from './src/mapping.mjs';
import { loadQuantum, resolveMapping, isColorVariable } from './src/lib.mjs';

const PKG = path.dirname(fileURLToPath(import.meta.url));
export const DIST = path.join(PKG, 'dist');
const pkg = JSON.parse(fs.readFileSync(path.join(PKG, 'package.json'), 'utf8'));

export const REGISTRY_SCHEMA = 'https://ui.shadcn.com/schema/registry-item.json';

const decl = (name, { value, trace }) => `  --${name}: ${value}; /* ${trace} */`;

/** dist/quantum.css from the resolved mapping. */
export function renderCss(theme, quantum) {
  const colors = Object.keys(mapping.VARIABLES).filter((n) => isColorVariable(mapping, quantum, n));
  return [
    `/*`,
    ` * Quantum for shadcn/ui (${pkg.name} ${pkg.version}): shadcn's theme variables, fed by the`,
    ` * Quantum design tokens (src/mapping.mjs). Generated by build.mjs: do not edit.`,
    ` * Import it after tailwindcss in your globals.css; dark mode is the \`dark\` class.`,
    ` */`,
    `:root {`,
    ...Object.entries(theme.light).map(([n, v]) => decl(n, v)),
    `}`,
    ``,
    `.dark {`,
    ...Object.entries(theme.dark).map(([n, v]) => decl(n, v)),
    `}`,
    ``,
    `@theme inline {`,
    ...colors.map((n) => `  --color-${n}: var(--${n});`),
    ...Object.entries(theme.theme).map(([n, v]) => decl(n, v)),
    `}`,
    ``,
  ].join('\n');
}

/** dist/quantum.json: the shadcn registry item (https://ui.shadcn.com/schema/registry-item.json). */
export function renderRegistryItem(theme) {
  const values = (o) => Object.fromEntries(Object.entries(o).map(([n, v]) => [n, v.value]));
  const tokens = (o) => Object.fromEntries(Object.entries(o).map(([n, v]) => [n, v.token]));
  return {
    $schema: REGISTRY_SCHEMA,
    name: 'quantum',
    type: 'registry:theme',
    title: 'Quantum',
    description: 'The Quantum Design System (Thales) theme: shadcn\'s theme variables fed by the Quantum design tokens, in light and dark.',
    author: 'Quantum Core Team <https://github.com/ThalesGroup/quantum>',
    cssVars: { theme: values(theme.theme), light: values(theme.light), dark: values(theme.dark) },
    meta: { package: `${pkg.name}@${pkg.version}`, tokens: { ...tokens(theme.light), ...tokens(theme.theme) } },
  };
}

/** Write dist/quantum.css and dist/quantum.json into `outDir`; returns what it wrote. */
export function buildTheme({ outDir = DIST, quantum = loadQuantum() } = {}) {
  const theme = resolveMapping(mapping, quantum);
  const css = renderCss(theme, quantum);
  const item = renderRegistryItem(theme);
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, 'quantum.css'), css);
  fs.writeFileSync(path.join(outDir, 'quantum.json'), `${JSON.stringify(item, null, 2)}\n`);
  return { theme, css, item, files: ['quantum.css', 'quantum.json'].map((f) => path.join(outDir, f)) };
}

/** Build demo/ into dist/demo.html with the package's own Vite. */
function buildDemo() {
  const vite = path.join(PKG, 'node_modules/.bin/vite');
  if (!fs.existsSync(vite)) throw new Error(`${path.relative(process.cwd(), vite)} is missing: install the workspace (pnpm install) to build the demo.`);
  const run = spawnSync(vite, ['build', '--config', path.join(PKG, 'demo/vite.config.ts'), '--logLevel', 'warn'], { cwd: PKG, stdio: 'inherit' });
  if (run.status !== 0) throw new Error(`vite build failed (exit ${run.status ?? run.signal})`);
}

function main() {
  fs.rmSync(DIST, { recursive: true, force: true });
  const { theme, files } = buildTheme();
  const rel = (f) => path.relative(process.cwd(), f);
  console.log(`${Object.keys(theme.light).length} variables (light), ${Object.keys(theme.dark).length} (dark), ${Object.keys(theme.theme).length} theme variables`);
  for (const f of files) console.log(`Wrote ${rel(f)}`);
  if (!process.argv.includes('--no-demo')) {
    buildDemo();
    console.log(`Wrote ${rel(path.join(DIST, 'demo.html'))}`);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main();
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
}
