#!/usr/bin/env node
/**
 * Components -> a Figma development plugin that draws them as component sets bound to Figma
 * variables (src/plan.mjs for the plan, src/plugin.js for the drawing).
 *
 *   node build.mjs [id…]    write dist/ (default: every component with a blueprint)
 *
 * dist/ holds manifest.json, code.js (the plugin with its plan), ui.html (the plugin window, built
 * with the design system: it reads the token CSS of packages/tokens/dist/, so run `pnpm
 * tokens:build` first, as `pnpm figma:export` and `pnpm build` do) and plan.json (the plan, to
 * read). In the Figma desktop app: Plugins > Development > Import plugin from manifest…, pick
 * packages/figma/dist/manifest.json, then run "Quantum components" in a design file. Not
 * committed (dist/ is ignored): `pnpm build` and `pnpm figma:export` write it again.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadAll } from '../../scripts/lib/dtcg.mjs';
import { MANIFEST, pluginPlan } from './src/plan.mjs';
import { BLUEPRINTS } from './src/blueprints/index.mjs';
import { renderUi, UI_COMPONENTS } from './src/ui/ui.mjs';
import { PATHS, FILES, artifacts } from '../../scripts/lib/paths.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = path.join(ROOT, PATHS.figmaDist);

function main() {
  const ids = process.argv.slice(2);
  const wanted = ids.length ? ids : Object.keys(BLUEPRINTS);
  const unknown = wanted.filter((id) => !BLUEPRINTS[id]);
  if (unknown.length) {
    console.error(`No Figma blueprint for ${unknown.join(', ')}. Components it can draw: ${Object.keys(BLUEPRINTS).join(', ')}.`);
    process.exit(1);
  }
  // The components whose instances a blueprint uses are drawn too, first.
  const drawn = new Set();
  const add = (id) => {
    if (drawn.has(id)) return;
    (BLUEPRINTS[id].uses ?? []).forEach(add);
    drawn.add(id);
  };
  wanted.forEach(add);
  const loaded = loadAll(path.join(ROOT, PATHS.tokens));
  const specs = [...drawn].map((id) => JSON.parse(fs.readFileSync(path.join(ROOT, artifacts(id).spec), 'utf8')));
  const plan = pluginPlan(loaded, specs, BLUEPRINTS);
  const plugin = fs.readFileSync(path.join(ROOT, PATHS.figma, 'src/plugin.js'), 'utf8');
  const read = (file) => {
    const full = path.join(ROOT, file);
    if (!fs.existsSync(full)) {
      console.error(`${file} is missing: run pnpm tokens:build first.`);
      process.exit(1);
    }
    return fs.readFileSync(full, 'utf8');
  };
  const ui = renderUi(plan, {
    fonts: read(FILES.webFontsCss),
    css: [
      `${PATHS.tokensCss}/raw.css`,
      `${PATHS.tokensCss}/semantic.css`,
      ...UI_COMPONENTS.map((id) => artifacts(id).generated),
      ...UI_COMPONENTS.map((id) => artifacts(id).css),
    ].map(read).join('\n'),
  });

  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(OUT, { recursive: true });
  fs.writeFileSync(path.join(OUT, 'manifest.json'), `${JSON.stringify(MANIFEST, null, 2)}\n`);
  fs.writeFileSync(path.join(OUT, 'ui.html'), ui);
  fs.writeFileSync(path.join(OUT, 'plan.json'), `${JSON.stringify(plan, null, 2)}\n`);
  fs.writeFileSync(path.join(OUT, 'code.js'), `// Generated by @quantum-ds/figma (build.mjs: ${[...drawn].join(', ')}): do not edit.\nconst PLAN = ${JSON.stringify(plan)};\n\n${plugin}`);

  const rel = path.relative(ROOT, OUT);
  for (const c of plan.components) console.log(`${c.name} ${c.version}: ${c.variants.length} variants${c.uncovered.length ? ` (not drawn, not listed: ${c.uncovered.join(', ')})` : ''}`);
  console.log(`${plan.variables.variables.length} variables in ${plan.variables.collections.map((c) => c.name).join(', ')}`);
  if (plan.variables.skipped.length) console.log(`${plan.variables.skipped.length} tokens left out: Figma has no variable type for them (durations, easings)`);
  console.log(`Wrote ${rel}/. In Figma: Plugins > Development > Import plugin from manifest… > ${rel}/manifest.json`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
